COLS = "(module_id, pattern_id, type, difficulty, concepts, step_count, has_trap, content, options, answer, solution, time_limit_sec, variant_of, variant_axis, source_type, source_ref)"

def _seed_exam_questions(cur, questions):
    """Insert exam questions into the database. Idempotent."""
    added = 0
    for q in questions:
        try:
            cur.execute(f"INSERT OR IGNORE INTO questions {COLS} VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)", q)
            if cur.rowcount > 0:
                added += 1
        except Exception as e:
            print(f"Error on question: {e}")
    return added

def add_questions():
    init_db()
    db = get_db()
    cur = db.cursor()
    added = _seed_exam_questions(cur, EXAM_QUESTIONS)
    db.commit()
    db.close()
    print(f"Added {added} new exam questions")

if __name__ == "__main__":
    add_questions()
